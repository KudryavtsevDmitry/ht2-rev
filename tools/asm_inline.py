r"""Turn a procedure of src/asm into a naked C++ function with an inline __asm body.

    py tools\asm_inline.py FILE.asm ENTRY CNAME OUT.cpp

Takes the whole _TEXT of FILE (it must hold only that procedure and its
pieces), renames the labels ($L_x / FUN_x -> L_x / L_FUN_x), points the data
references at KingRdata / KingData / KingBss and declares every function it
calls with the convention its decorated name gives. Appends the function
(extern "C", naked, cdecl name CNAME) to OUT.cpp. For code that has to stay
exactly as compiled in 1999 (x87 chains); the result is C++ for the build.
"""
import re
import sys
from pathlib import Path

src, entry, cname, out = sys.argv[1:5]
L = Path(src).read_text(encoding='utf-8').replace('\r\n', '\n').split('\n')
body = L[L.index('_TEXT SEGMENT') + 1:L.index('_TEXT ENDS')]

decls = {}


def declare(sym):
    if sym in ('_KingRdata', '_KingData', '_KingBss'):
        return sym[1:]
    if sym in ('__CIpow', '__ftol', '__CIsqrt', '__CIcos', '__CIsin', '__CIatan2', '__CIfmod'):
        decls[sym] = f'extern "C" void {sym[1:]}();'
        return sym[1:]
    m = re.fullmatch(r'@(\w+)@(\d+)', sym)
    if m:
        n = int(m[2]) // 4
        decls[sym] = f'extern "C" void __fastcall {m[1]}({", ".join(["int"] * n) or "void"});'
        return m[1]
    m = re.fullmatch(r'_(\w+)@(\d+)', sym)
    if m:
        n = int(m[2]) // 4
        decls[sym] = f'extern "C" void __stdcall {m[1]}({", ".join(["int"] * n) or "void"});'
        return m[1]
    m = re.fullmatch(r'_(\w+)', sym)
    if m:
        decls[sym] = f'extern "C" void __cdecl {m[1]}();'
        return m[1]
    raise SystemExit('unknown symbol ' + sym)


labels = set()
for line in body:
    m = re.match(r'^\s*([$\w]+)(?:\s+PROC\b|::?)', line)
    if m:
        labels.add(m[1])


def lab(name):
    return name[1:] if name.startswith('$L_') else 'L_' + name


asm = []
for line in body:
    code = line.split(';', 1)[0].rstrip()
    s = code.strip()
    if not s or re.match(r'^(ALIGN|EVEN)\b', s, re.I) or re.match(r'^\S+\s+ENDP\b', s):
        continue
    m = re.match(r'^([$\w]+)\s+PROC\b', s)
    if m:
        asm.append(lab(m[1]) + ':')
        continue
    m = re.match(r'^([$\w]+)::?\s*(.*)$', s)
    if m and m[1] in labels:
        asm.append(lab(m[1]) + ':')
        s = m[2]
        if not s:
            continue
    m = re.match(r'^BYTE\s+0?([0-9a-fA-F]+)H$', s, re.I)
    if m:
        asm.append('_emit 0x' + m[1][-2:])
        continue
    s = re.sub(r'\((_King(?:Rdata|Data|Bss))\+(\d+)\)', lambda m: m[1][1:] + '+' + m[2], s)

    def tokrep(m):
        t = m[0]
        if t in labels:
            return lab(t)
        if t.startswith(('_', '@')) and not t.startswith('__imp'):
            return declare(t)
        if t.startswith('__imp'):
            raise SystemExit('import call not supported: ' + line)
        return t
    s = re.sub(r'[A-Za-z_$?@][\w$?@]*', tokrep, s)
    asm.append(s)

text = [f'// [{entry}] kept as the original machine code (generated by tools/asm_inline.py from {Path(src).name})']
text += sorted(set(decls.values()))
text += [f'extern "C" __declspec(naked) void {cname}()', '{', '    __asm {']
text += ['        ' + a if not a.endswith(':') else '    ' + a for a in asm]
text += ['    }', '}', '']
o = Path(out)
old = o.read_text(encoding='utf-8') if o.exists() else ''
o.write_text(old + '\n'.join(text) + '\n', encoding='utf-8', newline='\n')
print(len(asm), 'lines,', len(decls), 'declarations')
