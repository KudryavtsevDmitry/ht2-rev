"""extract.py OUT FILE:NAME[,NAME...] ... - copies the named function definitions out of the source files
(from the definition line to the first '}' at column 0) for small_test.cpp"""
import re
import sys

out = ['// generated by tools/x87_test/extract.py from the game sources', 'KING_VAR(void*, g_players, 68b990)',
       'KING_VAR(BYTE*, g_68d4f4, 68d4f4)', '']
for arg in sys.argv[2:]:
    path, names = arg.rsplit(':', 1)
    lines = open(path, encoding='utf-8').read().split('\n')
    for name in names.split(','):
        i = next(k for k, l in enumerate(lines) if re.match(r'^(static|extern "C")\s.*\b%s\(' % name, l) and not l.rstrip().endswith(';'))
        j = next(k for k in range(i, len(lines)) if lines[k].startswith('}'))
        out += ['#line %d "%s"' % (i + 1, path.replace('\\', '/'))] + lines[i:j + 1] + ['']
open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
